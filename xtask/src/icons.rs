//! `gen-icons` and `update-icons`: the tables behind the `icon` and
//! `file_icon` template functions.
//!
//! The upstream inputs are checked in under `libbeachcomber/icons/`
//! (`glyphnames.json` from Nerd Fonts, two Lua tables from
//! nvim-web-devicons, their licences and a `VERSIONS` file). `gen-icons`
//! turns them into `libbeachcomber/src/library/icons/{nerd,files}.rs`;
//! `--check` fails if those files differ from what the inputs generate.
//! `update-icons` is the online step: it refetches the inputs at a pinned
//! Nerd Fonts tag and a pinned nvim-web-devicons commit, then regenerates.
//! Downloads are only ever read as data.

use std::path::{Path, PathBuf};

const DIR: &str = "libbeachcomber/icons";
const OUT: &str = "libbeachcomber/src/library/icons";
/// The glyph `file_icon` gives a file no table knows: the Nerd Fonts glyph
/// of this name.
const DEFAULT_NAME: &str = "fa-file";

type Table = Vec<(String, char)>;

/// `glyphnames.json`: the version in `METADATA` and the sorted `name -> char`.
fn parse_nerd(json: &str) -> Result<(String, Table), String> {
    let v: serde_json::Value =
        serde_json::from_str(json).map_err(|e| format!("glyphnames: {e}"))?;
    let obj = v.as_object().ok_or("glyphnames: not an object")?;
    let version = obj
        .get("METADATA")
        .and_then(|m| m.get("version"))
        .and_then(|v| v.as_str())
        .ok_or("glyphnames: no METADATA.version")?
        .to_string();
    let mut table = Table::new();
    for (name, e) in obj.iter().filter(|(k, _)| *k != "METADATA") {
        if !name
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
        {
            return Err(format!("glyphnames: odd name {name:?}"));
        }
        let ch = one_char(e.get("char").and_then(|c| c.as_str()).unwrap_or(""), name)?;
        let code = e.get("code").and_then(|c| c.as_str()).unwrap_or("");
        if u32::from_str_radix(code, 16).ok() != Some(ch as u32) {
            return Err(format!("glyphnames: {name}: code {code} is not its char"));
        }
        table.push((name.clone(), ch));
    }
    table.sort();
    Ok((version, table))
}

fn one_char(s: &str, what: &str) -> Result<char, String> {
    let mut it = s.chars();
    match (it.next(), it.next()) {
        (Some(c), None) => Ok(c),
        _ => Err(format!("{what}: glyph {s:?} is not one character")),
    }
}

/// The `["key"] = { icon = "glyph", ...}` rows of an nvim-web-devicons table.
/// Only the `icon` field is taken.
fn parse_lua(lua: &str) -> Result<Table, String> {
    let mut table = Table::new();
    for line in lua.lines() {
        let Some(rest) = line.trim_start().strip_prefix("[\"") else {
            continue;
        };
        let (key, rest) = rest
            .split_once("\"]")
            .ok_or_else(|| format!("bad row: {line}"))?;
        if key.contains('\\') || key.is_empty() {
            return Err(format!("unsupported key {key:?}"));
        }
        let glyph = rest
            .split_once("icon = \"")
            .and_then(|(_, g)| g.split_once('"'))
            .ok_or_else(|| format!("{key}: no icon"))?
            .0;
        table.push((key.to_string(), one_char(glyph, key)?));
    }
    table.sort();
    if let Some(w) = table.windows(2).find(|w| w[0].0 == w[1].0) {
        return Err(format!("duplicate key {:?}", w[0].0));
    }
    Ok(table)
}

fn lit(c: char) -> String {
    format!("'\\u{{{:x}}}'", c as u32)
}

fn array(name: &str, ty: &str, items: impl Iterator<Item = String>) -> String {
    let items: Vec<String> = items.collect();
    let mut out = format!(
        "#[rustfmt::skip]\npub(super) static {name}: [{ty}; {}] = [\n",
        items.len()
    );
    for chunk in items.chunks(12) {
        out += &format!("    {},\n", chunk.join(", "));
    }
    out + "];\n"
}

fn gen_nerd(version: &str, table: &Table, versions: &str) -> String {
    let blob: String = table.iter().map(|(n, _)| n.as_str()).collect();
    let mut end = 0u32;
    let ends = table.iter().map(|(n, _)| {
        end += n.len() as u32;
        end.to_string()
    });
    let mut out = format!(
        "//! @generated by `cargo xtask gen-icons` from libbeachcomber/icons/ ({}). Do not edit.\n\n\
         /// The Nerd Fonts version the names are from.\npub const VERSION: &str = \"{version}\";\n\n\
         /// Every name, sorted bytewise, back to back; `ENDS[i]` is where name `i` ends.\n\
         #[rustfmt::skip]\npub(super) static NAMES: &str = \"{blob}\";\n\n",
        versions.lines().collect::<Vec<_>>().join("; ")
    );
    out += &array("ENDS", "u32", ends);
    out += "\n/// The code point of each name.\n";
    out += &array(
        "CODES",
        "u32",
        table.iter().map(|(_, c)| format!("0x{:x}", *c as u32)),
    );
    out
}

fn gen_files(by_name: &Table, by_ext: &Table, default: char) -> String {
    let rows = |t: &Table| -> String {
        t.iter()
            .map(|(k, c)| format!("    ({k:?}, {}),\n", lit(*c)))
            .collect()
    };
    format!(
        "//! @generated by `cargo xtask gen-icons` from libbeachcomber/icons/. Do not edit.\n\n\
         /// The glyph of a file no table knows.\npub(super) const DEFAULT: char = {};\n\n\
         /// By whole basename, sorted bytewise.\n#[rustfmt::skip]\npub(super) static BY_NAME: [(&str, char); {}] = [\n{}];\n\n\
         /// By extension (dots inside it allowed), sorted bytewise.\n#[rustfmt::skip]\npub(super) static BY_EXT: [(&str, char); {}] = [\n{}];\n",
        lit(default),
        by_name.len(),
        rows(by_name),
        by_ext.len(),
        rows(by_ext),
    )
}

fn read(root: &Path, rel: &str) -> Result<String, String> {
    std::fs::read_to_string(root.join(rel)).map_err(|e| format!("reading {rel}: {e}"))
}

/// The two generated files as (path, content), from the checked-in inputs.
fn generate(root: &Path) -> Result<Vec<(PathBuf, String)>, String> {
    let (version, nerd) = parse_nerd(&read(root, &format!("{DIR}/glyphnames.json"))?)?;
    let versions = read(root, &format!("{DIR}/VERSIONS"))?;
    let by_name = parse_lua(&read(root, &format!("{DIR}/icons_by_filename.lua"))?)?;
    let by_ext = parse_lua(&read(root, &format!("{DIR}/icons_by_file_extension.lua"))?)?;
    let default = nerd
        .iter()
        .find(|(n, _)| n == DEFAULT_NAME)
        .ok_or(format!("no Nerd Fonts glyph {DEFAULT_NAME}"))?
        .1;
    Ok(vec![
        (
            root.join(OUT).join("nerd.rs"),
            gen_nerd(&version, &nerd, &versions),
        ),
        (
            root.join(OUT).join("files.rs"),
            gen_files(&by_name, &by_ext, default),
        ),
    ])
}

pub fn gen_icons(root: &Path, check: bool) -> Result<(), String> {
    for (path, content) in generate(root)? {
        if check {
            if std::fs::read_to_string(&path).ok().as_deref() != Some(&content) {
                return Err(format!(
                    "{} does not match libbeachcomber/icons/ -- run `cargo xtask gen-icons` and commit the result",
                    path.display()
                ));
            }
        } else {
            std::fs::write(&path, content)
                .map_err(|e| format!("writing {}: {e}", path.display()))?;
            println!("Wrote {}", path.display());
        }
    }
    Ok(())
}

fn fetch(url: &str, to: &Path) -> Result<(), String> {
    let status = std::process::Command::new("curl")
        .args(["-fsSL", "-o"])
        .arg(to)
        .arg(url)
        .status()
        .map_err(|e| format!("running curl: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("fetching {url} failed"))
    }
}

/// Refetch the inputs at `nerd_tag` and `devicons_commit`, then regenerate.
pub fn update_icons(root: &Path, nerd_tag: &str, devicons_commit: &str) -> Result<(), String> {
    for (what, v) in [("tag", nerd_tag), ("commit", devicons_commit)] {
        if v.is_empty()
            || !v
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b == b'.' || b == b'-')
        {
            return Err(format!("`{v}` is not a {what}"));
        }
    }
    let dir = root.join(DIR);
    let nerd = format!("https://raw.githubusercontent.com/ryanoasis/nerd-fonts/{nerd_tag}");
    let dev =
        format!("https://raw.githubusercontent.com/nvim-tree/nvim-web-devicons/{devicons_commit}");
    let d = |f: &str| format!("{dev}/lua/nvim-web-devicons/default/{f}.lua");
    fetch(
        &format!("{nerd}/glyphnames.json"),
        &dir.join("glyphnames.json"),
    )?;
    fetch(&format!("{nerd}/LICENSE"), &dir.join("LICENSE-nerd-fonts"))?;
    fetch(
        &format!("{dev}/LICENSE"),
        &dir.join("LICENSE-nvim-web-devicons"),
    )?;
    for f in ["icons_by_filename", "icons_by_file_extension"] {
        fetch(&d(f), &dir.join(format!("{f}.lua")))?;
    }
    std::fs::write(
        dir.join("VERSIONS"),
        format!("nerd-fonts {nerd_tag}\nnvim-web-devicons {devicons_commit}\n"),
    )
    .map_err(|e| format!("writing VERSIONS: {e}"))?;
    println!(
        "Fetched. Check both LICENSE files are still MIT, then add a CHANGELOG line naming the versions."
    );
    gen_icons(root, false)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .to_path_buf()
    }

    #[test]
    fn gen_icons_check_passes_on_the_committed_tables() {
        gen_icons(&root(), true).unwrap();
    }

    #[test]
    fn parse_lua_takes_the_icon_field_and_sorts() {
        let t = parse_lua("return {\n  [\"b\"] = { icon = \"\u{e702}\", color = \"#fff\" },\n  [\"a\"]  = { icon = \"x\" },\n}\n").unwrap();
        assert_eq!(t, vec![("a".into(), 'x'), ("b".into(), '\u{e702}')]);
    }

    #[test]
    fn parse_lua_refuses_duplicates_and_wide_glyphs() {
        assert!(parse_lua("[\"a\"] = { icon = \"x\" },\n[\"a\"] = { icon = \"y\" },\n").is_err());
        assert!(parse_lua("[\"a\"] = { icon = \"xy\" },\n").is_err());
    }
}
